sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rl_waltmann"))
from generate_gen_plots import plot_bandit_choice_trends_single_axis, REVERSAL_POINTS as WALTMANN_REVERSAL_POINTS

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(SCRIPT_DIR, "data")
FIGURES_DIR = os.path.join(SCRIPT_DIR, "figures")
