ground_truth_label = "Ground-truth agent" if args.data_source == "simulated" else "Real data"
print(f"{ground_truth_label}: peak choice(A) ~ {data_rate_A[10:REVERSAL].mean():.2f}, "
      f"late choice(A) ~ {data_rate_A[-10:].mean():.2f}")
print(f"Fitted Repetition: rho = {rho_fits.mean():.3f}")
print(f"Fitted WSLS (single parameter): P = {wsls_P_fits.mean():.3f}")
print(f"Mean predictive log-lik/trial: Repetition={ll_rep_bar:.3f}, WSLS={ll_wsls_bar:.3f}")

