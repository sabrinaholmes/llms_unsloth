"""
Replicates the two-panel reversal-learning figure, following the procedure
in Palminteri, Wyart & Koechlin (2017, Trends in Cognitive Sciences, Box 1
/ Figure I): ground-truth choice data are generated by a Q-learning agent
(learning rate alpha) whose latent values are corrupted by additive
Gaussian noise (std sigma) at the moment of choice. Two single-parameter
heuristic models are then compared:
  (A, left)  Predictive performance: Repetition & WS-LS models fit to /
             fed the "real" (Q-learning-agent-generated) choice-outcome
             history, scored on next-choice prediction, with a
             log-likelihood inset comparing the two models.
  (A, right) Generative performance: same fitted models run forward on
             their own (using only the task's true reward contingencies)
             to see what behavior they produce from scratch.

Run: python3 reversal_learning_figure.py [--no_loglik_bars] [--no_title] [--legend {all,predictive,none}]
Outputs: CSVs in data/, PNGs in figures/ (legends saved separately as *_legend.png)
"""

