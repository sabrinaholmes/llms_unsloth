COL_HIGH = "#7b2d8b"    # purple (80% option)
COL_LOW = "#3b5aa0"     # blue (20% option)

rng = np.random.default_rng(42)
random.seed(42)  # ProbabilisticWinStayLoseSwitch uses stdlib `random` internally

# Filename tag + data-curve legend label, so simulated and real-data runs write to
# separate files instead of overwriting each other's outputs.
TAG = "" if args.data_source == "simulated" else "_real"

# ----------------------------------------------------------------------
# 1. Ground-truth "real" data: either simulated from a Q-learning agent, or
#    loaded from real subjects' choice/reward histories (--data_source=real).
#    REVERSAL_POINTS_1IDX is the 1-indexed trial number of the first trial of
#    each new block; REVERSAL_POINTS_0IDX is the same, 0-indexed, as consumed
#    by reward_prob_A/B and simulate_generative_wsls.
# ----------------------------------------------------------------------
if args.data_source == "real":
    choices, rewards, subject_ids, N_TRIALS, REVERSAL_POINTS_0IDX = load_waltmann_data(
        REAL_DATA_CSV, reversal_points_1idx=WALTMANN_REVERSAL_POINTS)
    N_SUBJECTS = len(subject_ids)
    REVERSAL_POINTS_1IDX = tuple(WALTMANN_REVERSAL_POINTS)
    REVERSAL = REVERSAL_POINTS_0IDX[0]
    print(f"Loaded real data: {N_SUBJECTS} subjects, {N_TRIALS} trials, "
          f"reversals at {REVERSAL_POINTS_1IDX} from {REAL_DATA_CSV}")
else:
    choices, rewards = simulate_qlearning_agent(N_SUBJECTS, ALPHA_TRUE, NOISE_SD_TRUE, rng)
    REVERSAL_POINTS_0IDX = (REVERSAL,)
    REVERSAL_POINTS_1IDX = (REVERSAL + 1,)

# Trial range shown in the plots only (fitting above/below always uses the full
# N_TRIALS). Real data defaults to first-reversal + 14 trials -- enough to see
# the post-reversal dip and recovery -- rather than all 5 Waltmann blocks at once.
if args.max_trial is not None:
    PLOT_MAX_TRIAL = args.max_trial
elif args.data_source == "real":
    PLOT_MAX_TRIAL = min(N_TRIALS, REVERSAL_POINTS_1IDX[0] + 14)
else:
    PLOT_MAX_TRIAL = N_TRIALS

data_rate_A = (choices == 0).mean(axis=0)
data_sem_A = (choices == 0).std(axis=0) / np.sqrt(N_SUBJECTS)

# ----------------------------------------------------------------------
# 2. Fit models per subject on real data; build predictive curves
# ----------------------------------------------------------------------
pred_rep = np.zeros((N_SUBJECTS, N_TRIALS))
pred_wsls = np.zeros((N_SUBJECTS, N_TRIALS))
ll_rep = np.zeros(N_SUBJECTS)
ll_wsls = np.zeros(N_SUBJECTS)

rho_fits = np.zeros(N_SUBJECTS)
wsls_P_fits = np.zeros(N_SUBJECTS)

for s in range(N_SUBJECTS):
    c, r = choices[s], rewards[s]

    rho = fit_repetition(c)
    p_rep = predictive_curve_repetition(c, rho)
    pred_rep[s] = p_rep
    ll_rep[s] = mean_trial_loglik(c, p_rep)
    rho_fits[s] = rho

    P = fit_wsls(c, r)
    p_wsls = predictive_curve_wsls(c, r, P)
    pred_wsls[s] = p_wsls
    ll_wsls[s] = mean_trial_loglik(c, p_wsls)
    wsls_P_fits[s] = P

pred_rep_mean = pred_rep.mean(axis=0)
pred_rep_sem = pred_rep.std(axis=0) / np.sqrt(N_SUBJECTS)
pred_wsls_mean = pred_wsls.mean(axis=0)
pred_wsls_sem = pred_wsls.std(axis=0) / np.sqrt(N_SUBJECTS)

ll_rep_bar = ll_rep.mean()
ll_wsls_bar = ll_wsls.mean()

# ----------------------------------------------------------------------
# 3. Generative simulations using each subject's fitted parameters
# ----------------------------------------------------------------------
gen_rep_all = np.zeros((N_SUBJECTS * N_GEN_SIMS_PER_SUBJECT, N_TRIALS))
gen_wsls_all = np.zeros((N_SUBJECTS * N_GEN_SIMS_PER_SUBJECT, N_TRIALS))

for s in range(N_SUBJECTS):
    sl = slice(s * N_GEN_SIMS_PER_SUBJECT, (s + 1) * N_GEN_SIMS_PER_SUBJECT)
    gen_rep_all[sl] = simulate_generative_repetition(rho_fits[s], N_GEN_SIMS_PER_SUBJECT, rng, n_trials=N_TRIALS)
    gen_wsls_all[sl] = simulate_generative_wsls(wsls_P_fits[s], N_GEN_SIMS_PER_SUBJECT, rng,
                                                 n_trials=N_TRIALS, reversal_points=REVERSAL_POINTS_0IDX)

gen_rep_rate = (gen_rep_all == 0).mean(axis=0)
gen_rep_sem = (gen_rep_all == 0).std(axis=0) / np.sqrt(gen_rep_all.shape[0])
gen_wsls_rate = (gen_wsls_all == 0).mean(axis=0)
gen_wsls_sem = (gen_wsls_all == 0).std(axis=0) / np.sqrt(gen_wsls_all.shape[0])


def _to_long_df(arr, transform=lambda a: a):
    """(n_runs, N_TRIALS) array -> long df with columns model_id/trial_num/
    chose_preferred, the shape rl_waltmann's aggregate_trend/
    plot_bandit_choice_trends_single_axis expect."""
    n_runs, n_trials = arr.shape
    return pd.DataFrame({
        "model_id": np.repeat(np.arange(n_runs), n_trials),
        "trial_num": np.tile(np.arange(1, n_trials + 1), n_runs),
        "chose_preferred": transform(arr).flatten(),
    })


